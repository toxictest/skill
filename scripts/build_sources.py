TEMPLATE = """# {id}. {title}

- **URL**: {url}
- **Category**: {cat}
- **Verdict**: {verdict}

## What it is
{what}

## How super-skill uses it
{use}

## Status in this skill
Covered in ANALYSIS.md (section mapping) and routed via the matching
playbook under `playbooks/`. Regenerate this file with
`python3 scripts/build_sources.py`.
"""


def main() -> int:
    out_dir = Path(__file__).resolve().parent.parent / "sources"
    out_dir.mkdir(exist_ok=True)
    for eid, slug, title, url, cat, verdict, what, use in ENTRIES:
        path = out_dir / f"{eid}-{slug}.md"
        path.write_text(
            TEMPLATE.format(
                id=eid, title=title, url=url, cat=cat,
                verdict=VERDICT_LABEL[verdict], what=what, use=use,
            ),
            encoding="utf-8",
        )
    # index file
    lines = ["# Sources Index — one file per supplied link\n",
             f"Generated: {len(ENTRIES)} files. Missing numbers: 7 (never in the list).\n",
             "| # | File | Verdict |", "|---|---|---|"]
    for eid, slug, title, url, cat, verdict, *_ in ENTRIES:
        lines.append(f"| {eid} | [{slug}](./{eid}-{slug}.md) | {VERDICT_LABEL[verdict]} |")
    (out_dir / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(ENTRIES)} files + README.md -> {out_dir}")
    return 0


