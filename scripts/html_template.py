#!/usr/bin/env python3
"""Scaffold a preview-safe single-file HTML page — super-skill coding-dev playbook.

The Arena preview iframe has NO network access, so this template uses only
inline CSS/SVG — no CDNs, no external fonts/images.

Usage:  html_template.py "Page Title" [output.html] [--dark] [--accent #4f46e5]
"""
import argparse
import sys
from pathlib import Path

TEMPLATE = """<!DOCTYPE html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>
  :root {{ --accent: {accent}; --bg: {bg}; --fg: {fg}; --muted: {muted}; --card: {card}; }}
  * {{ box-sizing: border-box; margin: 0; padding: 0; }}
  body {{ font-family: system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
         background: var(--bg); color: var(--fg); line-height: 1.6; padding: 2rem; }}
  header {{ max-width: 900px; margin: 0 auto 1.5rem; }}
  h1 {{ font-size: 1.8rem; margin-bottom: .25rem; }}
  h1 span {{ color: var(--accent); }}
  .sub {{ color: var(--muted); font-size: .95rem; }}
  main {{ max-width: 900px; margin: 0 auto; display: grid;
          grid-template-columns: repeat(auto-fit, minmax(240px, 1fr)); gap: 1rem; }}
  .card {{ background: var(--card); border: 1px solid {border};
           border-radius: 12px; padding: 1.1rem; }}
  .card h2 {{ font-size: 1.05rem; margin-bottom: .5rem; }}
  .card p {{ color: var(--muted); font-size: .92rem; }}
  .badge {{ display: inline-block; background: var(--accent); color: #fff;
            font-size: .72rem; padding: .15rem .55rem; border-radius: 999px;
            margin-bottom: .6rem; letter-spacing: .03em; }}
  footer {{ max-width: 900px; margin: 2rem auto 0; color: var(--muted);
            font-size: .82rem; text-align: center; }}
  svg {{ display: block; }}
</style>
</head>
<body>
<header>
  <h1>{title_head}</h1>
  <p class="sub">{subtitle}</p>
</header>
<main>
  <section class="card">
    <span class="badge">STEP 1</span>
    <h2>Card title</h2>
    <p>Replace this with real content. Inline SVG works offline in preview.</p>
    <svg width="40" height="40" viewBox="0 0 24 24" fill="none"
         stroke="{accent}" stroke-width="2" aria-hidden="true">
      <circle cx="12" cy="12" r="9"/><path d="M12 7v5l3 3"/>
    </svg>
  </section>
  <section class="card">
    <span class="badge">STEP 2</span>
    <h2>Card title</h2>
    <p>No CDN stylesheets, fonts, or images — the preview runs sandboxed.</p>
  </section>
  <section class="card">
    <span class="badge">STEP 3</span>
    <h2>Card title</h2>
    <p>The downloaded copy behaves identically because everything is inline.</p>
  </section>
</main>
<footer>Generated by super-skill · preview-safe single file</footer>
</body>
</html>
"""


def main() -> int:
    ap = argparse.ArgumentParser(description="Preview-safe HTML scaffold")
    ap.add_argument("title", help="page title")
    ap.add_argument("output", nargs="?", default="index.html", help="output path")
    ap.add_argument("--dark", action="store_true", help="dark theme")
    ap.add_argument("--accent", default="#4f46e5", help="accent color hex")
    ap.add_argument("--lang", default="en", help="html lang attribute")
    ap.add_argument("--subtitle", default="Built with super-skill — fully offline preview",
                    help="subtitle text")
    args = ap.parse_args()

    if args.dark:
        bg, fg, muted, card, border = "#0f1115", "#e8eaf0", "#9aa0ae", "#171a21", "#2a2f3a"
    else:
        bg, fg, muted, card, border = "#f6f7fb", "#1a1d24", "#5c6270", "#ffffff", "#e4e7ee"

    head, _, tail = args.title.partition(" — ")
    title_head = f"{head}<span> — {tail}</span>" if tail else args.title

    out = Path(args.output)
    out.write_text(
        TEMPLATE.format(
            lang=args.lang, title=args.title, title_head=title_head,
            subtitle=args.subtitle, accent=args.accent, bg=bg, fg=fg,
            muted=muted, card=card, border=border,
        ),
        encoding="utf-8",
    )
    print(f"wrote {out} ({out.stat().st_size} bytes) — open via present_file / preview")
    return 0


if __name__ == "__main__":
    sys.exit(main())
